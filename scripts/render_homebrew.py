#!/usr/bin/env python3
"""Render a binary-only Homebrew formula from a verified release manifest."""
import argparse
import json
from pathlib import Path
import re
import sys

from release import ReleaseError, SCHEMA, SOURCE_REPOSITORY, TARGETS, archive_stem, validate_version


def render(manifest: dict) -> str:
    version = validate_version(manifest.get("version"))
    if manifest.get("schema_version") != SCHEMA:
        raise ReleaseError("unsupported release manifest schema")
    entries = manifest.get("artifacts")
    if not isinstance(entries, list) or len(entries) != len(TARGETS):
        raise ReleaseError("formula requires the exact four-target manifest")
    hashes = {}
    for item in entries:
        target = item.get("target")
        if target not in TARGETS or target in hashes:
            raise ReleaseError("manifest has an unsupported or duplicate target")
        if (item.get("schema_version") != SCHEMA or item.get("version") != version
                or item.get("archive") != f"{archive_stem(version, target)}.tar.gz"
                or not isinstance(item.get("sha256"), str)
                or not re.fullmatch(r"[0-9a-f]{64}", item["sha256"])):
            raise ReleaseError("invalid artifact metadata or checksum")
        hashes[target] = item["sha256"]
    lines = [
        "# Generated by WhiteKiwi/loboot scripts/render_homebrew.py; do not edit hashes by hand.",
        "class Loboot < Formula",
        '  desc "Explicit native user-service management without a daemon"',
        f'  homepage "{SOURCE_REPOSITORY}"',
        '  license any_of: ["MIT", "Apache-2.0"]',
        "", "  livecheck do",
        '    skip "Updated from verified release assets by the tap workflow"',
        "  end",
    ]
    for os_name, suffix in (("macos", "apple-darwin"), ("linux", "unknown-linux-gnu")):
        lines += ["", f"  on_{os_name} do"]
        for cpu, arch in (("arm", "aarch64"), ("intel", "x86_64")):
            target = f"{arch}-{suffix}"
            archive = f"{archive_stem(version, target)}.tar.gz"
            lines += [f"    on_{cpu} do", f'      url "{SOURCE_REPOSITORY}/releases/download/v{version}/{archive}"',
                      f'      sha256 "{hashes[target]}"', "    end"]
        lines += ["  end"]
    lines += ["", "  def install", '    bin.install "loboot"',
              '    doc.install "README.md", "LICENSE-STATUS.txt", "THIRD-PARTY-LICENSES.txt", "RUST-COPYRIGHT.html"',
              "  end", "", "  test do", '    assert_match "loboot #{version}", shell_output("#{bin}/loboot --version")',
              '    assert_match "Usage:", shell_output("#{bin}/loboot --help")',
              '    root = testpath/"offline"',
              '    platform = OS.mac? ? "macos" : "linux"',
              '    output = shell_output("#{bin}/loboot --json --root #{root} --platform #{platform} doctor")',
              '    result = JSON.parse(output)',
              '    assert_equal "loboot.cli/v1", result.fetch("schema_version")',
              '    assert_equal true, result.fetch("ok")',
              '    assert_equal false, result.fetch("data").fetch("session").fetch("checked")',
              '    refute_path_exists root', "  end", "end", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        result = render(json.loads(args.manifest.read_text()))
        with args.output.open("x", encoding="utf-8") as output:
            output.write(result)
    except (ValueError, OSError, TypeError, KeyError) as error:
        print(f"homebrew: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
